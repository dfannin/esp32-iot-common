#!/usr/bin/env python3
"""web_embed.py - compress web files into a C header for the ESP32 (gzip, PROGMEM).

The pages are edited as real .html / .css / .js files and served compressed
(Content-Encoding: gzip) straight from flash. Run after editing them:

    python3 tools/web_embed.py src/iot_web_assets.h IOT_WEB web/page.html web/style.css web/app.js

A device embeds its own script the same way (its CI runs --check):

    python3 ~/Arduino/libraries/esp32-iot-common/tools/web_embed.py src/web_device.h DEVICE web/device.js

--check compares the header with the files (by content, after decompressing),
so it does not depend on the zlib version that produced the bytes.
"""

import argparse
import gzip
import pathlib
import re
import sys

TYPES = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
    ".json": "application/json",
    ".svg": "image/svg+xml",
}


def symbol(prefix: str, path: pathlib.Path) -> str:
    return prefix + "_" + re.sub(r"[^A-Za-z0-9]", "_", path.name).upper()


def render(prefix: str, files: list[pathlib.Path]) -> str:
    out = [
        "// Generated by esp32-iot-common tools/web_embed.py; do not edit.",
        "// Sources: " + ", ".join(f.as_posix() for f in files),
        "// Regenerate after editing them; CI runs web_embed.py --check.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "",
    ]
    for f in files:
        data = f.read_bytes()
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        name = symbol(prefix, f)
        out.append(f"// {f.name}: {len(data)} bytes, {len(gz)} gzipped")
        out.append(f"static const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(gz), 16):
            out.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const size_t {name}_LEN = {len(gz)};")
        out.append(f'static const char {name}_TYPE[] = "{TYPES.get(f.suffix, "application/octet-stream")}";')
        out.append("")
    return "\n".join(out)


def check(header: pathlib.Path, prefix: str, files: list[pathlib.Path]) -> list[str]:
    if not header.exists():
        return [f"{header} does not exist"]
    text = header.read_text()
    problems = []
    for f in files:
        name = symbol(prefix, f)
        m = re.search(rf"{name}\[\] PROGMEM = \{{(.*?)\}};", text, re.S)
        if not m:
            problems.append(f"{name} missing from {header}")
            continue
        gz = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m.group(1)))
        if gzip.decompress(gz) != f.read_bytes():
            problems.append(f"{header}: {name} is out of date with {f}")
    return problems


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="fail if the header is out of date")
    p.add_argument("header", type=pathlib.Path)
    p.add_argument("prefix")
    p.add_argument("files", type=pathlib.Path, nargs="+")
    a = p.parse_args()
    if a.check:
        problems = check(a.header, a.prefix, a.files)
        for msg in problems:
            print(msg, file=sys.stderr)
        if problems:
            print(f"Run: python3 tools/web_embed.py {a.header} {a.prefix} " + " ".join(map(str, a.files)), file=sys.stderr)
            return 1
        print(f"{a.header} is up to date")
        return 0
    a.header.write_text(render(a.prefix, a.files))
    for f in a.files:
        print(f"{f}: {f.stat().st_size} bytes -> {symbol(a.prefix, f)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
